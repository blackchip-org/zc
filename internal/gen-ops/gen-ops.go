type ValDoc struct {
	Label string
	Kind  string
	Var   bool
}

var (
	RootDir  = path.Join("..", "..")
	DocDir   = path.Join(RootDir, "doc", "ops")
	KindsDir = path.Join(RootDir, "kinds")
	OpsDir   = path.Join(RootDir, "ops")
	TestDir  = path.Join(RootDir, "test", "docs")
	VolDir   = path.Join(RootDir, "volumes")
)

func main() {
	docs, err := zc.LoadDocs()
	if err != nil {
		log.Panic(err)
	}
	genOpsConst(docs)
	genKinds(docs)
	genOps(docs)
	genVols(docs)
	genTests(docs)
}

func genOpsConst(docs []zc.VolDoc) {
	nameSet := make(map[string]struct{})
	for _, vol := range docs {
		for _, op := range vol.Ops {
			nameSet[op.Name] = struct{}{}
			for _, a := range op.Aliases {
				nameSet[a] = struct{}{}
			}
		}
	}
	names := maps.Keys(nameSet)
	sort.Strings(names)

	os.Mkdir(OpsDir, 0755)
	f, err := os.Create(path.Join(OpsDir, "ops.go"))
	if err != nil {
		log.Panic(err)
	}
	defer f.Close()

	fmt.Fprintf(f, "package ops\n\n")
	fmt.Fprintf(f, "// Code generated by 'gen-ops'; DO NOT EDIT.\n\n")
	fmt.Fprintf(f, "var (\n")

	for _, name := range names {
		var s scan.Scanner
		s.InitFromString("", name)

		// Skip any names that are only symbols
		if !scan.IsLetter(s.This) {
			continue
		}
		s.Val.WriteRune(unicode.ToUpper(s.This))
		s.Skip()

		for s.HasMore() {
			if s.Next == '.' || s.Next == '-' {
				s.Keep()
				s.Skip()
				s.Val.WriteRune(unicode.ToUpper(s.This))
				s.Skip()
			} else {
				s.Keep()
			}
		}
		fmt.Fprintf(f, "\t%v = \"%v\"\n", s.Emit().Val, name)
	}
	fmt.Fprintf(f, ")\n")
}

func genOps(vols []zc.VolDoc) {
	for _, vol := range vols {
		if len(vol.Ops) == 0 {
			continue
		}
		f, err := os.Create(path.Join(VolDir, vol.Package, "ops.go"))
		if err != nil {
			log.Panic(err)
		}
		defer f.Close()

		fmt.Fprintf(f, "package %v\n\n", vol.Package)
		fmt.Fprintf(f, "// Code generated by 'gen-ops'; DO NOT EDIT.\n\n")
		fmt.Fprintf(f, "import (\n")
		fmt.Fprintf(f, "\"github.com/blackchip-org/zc/v6\"\n")
		fmt.Fprintf(f, "\"github.com/blackchip-org/zc/v6/kinds\"\n")
		fmt.Fprintf(f, ")\n")

		fmt.Fprintf(f, "var (\n")
		for _, op := range vol.Ops {
			opIdent, ok := opIdent(op.Name)
			if !ok {
				log.Panicf("cannot create identifier for %v", op.Name)
			}
			fmt.Fprintf(f, "%v = zc.Op{\n", opIdent)
			fmt.Fprintf(f, "Name: \"%v\",\n", op.Name)
			fmt.Fprintf(f, "Aliases: []string{\n")
			for _, a := range op.Aliases {
				fmt.Fprintf(f, "\"%v\",\n", a)
			}
			fmt.Fprintf(f, "},\n")
			genValList(f, "Params", "VarParams", op.Params)
			genValList(f, "Returns", "VarReturns", op.Returns)
			if op.Prec != "" {
				fmt.Fprintf(f, "Prec: kinds.Prec%v,\n", op.Prec)
			}
			fmt.Fprintf(f, "Func: %v,\n", op.Func)
			fmt.Fprintf(f, "}\n")
		}
		fmt.Fprintf(f, ")\n")
	}
}

func genVols(vols []zc.VolDoc) {
	for _, vol := range vols {
		f, err := os.Create(path.Join(VolDir, vol.Package, "volume.go"))
		if err != nil {
			log.Panic(err)
		}
		defer f.Close()

		fmt.Fprintf(f, "package %v\n\n", vol.Package)
		fmt.Fprintf(f, "// Code generated by 'gen-ops'; DO NOT EDIT.\n\n")
		fmt.Fprintf(f, "import (\n")
		fmt.Fprintf(f, "\"github.com/blackchip-org/zc/v6\"\n")
		fmt.Fprintf(f, ")\n")

		fmt.Fprintf(f, "var Volume = zc.Vol{\n")
		fmt.Fprintf(f, "Name: \"%v\",\n", vol.Name)
		fmt.Fprintf(f, "Kinds: []zc.Kind{\n")
		for _, k := range vol.Kinds {
			fmt.Fprintf(f, "%vKind,\n", k)
		}
		fmt.Fprintf(f, "},\n")
		fmt.Fprintf(f, "Ops: []zc.Op{\n")
		for _, o := range vol.Ops {
			name, ok := opIdent(o.Name)
			if !ok {
				log.Panicf("cannot create identifier for %v", o.Name)
			}
			fmt.Fprintf(f, "%v,\n", name)
		}
		fmt.Fprintf(f, "},\n")
		fmt.Fprintf(f, "}\n")
	}
}

func genKinds(vols []zc.VolDoc) {
	kinds := []string{"Val"}
	for _, vol := range vols {
		kinds = append(kinds, vol.Kinds...)
	}
	slices.Sort(kinds)

	f, err := os.Create(path.Join(KindsDir, "kinds.go"))
	if err != nil {
		log.Panic(err)
	}
	defer f.Close()

	fmt.Fprintf(f, "package kinds\n\n")
	fmt.Fprintf(f, "// Code generated by 'gen-ops'; DO NOT EDIT.\n\n")
	fmt.Fprintf(f, "var (\n")
	for _, k := range kinds {
		fmt.Fprintf(f, "%v = \"%v\"\n", k, k)
	}
	fmt.Fprintf(f, ")\n")
}

