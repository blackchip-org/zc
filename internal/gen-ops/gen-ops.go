func parseValDoc(v string) ValDoc {
	s := scan.NewScannerFromString("", v)
	var val ValDoc
	for s.HasMore() {
		if s.This == ':' {
			s.Skip()
			val.Label = s.Emit().Val
		} else if s.This == '*' && s.Next == scan.EndOfText {
			s.Skip()
			val.Var = true
		} else {
			s.Keep()
		}
	}
	val.Kind = s.Emit().Val
	return val
}

func genValList(f *os.File, name string, varName string, vals []string) {
	fmt.Fprintf(f, "%v: []string{", name)

	var variable bool
	var list []string
	for _, v := range vals {
		valDoc := parseValDoc(v)
		list = append(list, fmt.Sprintf("kinds.%v", valDoc.Kind))
		if valDoc.Var {
			variable = true
		}
	}
	fmt.Fprintf(f, "%v},\n", strings.Join(list, ", "))
	if variable {
		fmt.Fprintf(f, "%v: true,\n", varName)
	}
}

func opIdent(name string) (string, bool) {
	var s scan.Scanner
	s.InitFromString("", name)

	// Skip any names that are only symbols
	if !scan.IsLetter(s.This) {
		return "", false
	}
	s.Val.WriteRune(unicode.ToUpper(s.This))
	s.Skip()

	for s.HasMore() {
		if s.Next == '.' || s.Next == '-' {
			s.Keep()
			s.Skip()
			s.Val.WriteRune(unicode.ToUpper(s.This))
			s.Skip()
		} else {
			s.Keep()
		}
	}
	return s.Emit().Val, true
}
