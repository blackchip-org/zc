func maxUintBig() *big.Int {
	bi := new(big.Int)
	bi.SetUint64(math.MaxUint)
	return bi
}

func maxUintBigPlus1() *big.Int {
	one := big.NewInt(1)
	max := maxUintBig()
	max.Add(max, one)
	return max
}

